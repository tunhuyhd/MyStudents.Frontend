/** One library, two intentional weights: expressive content and crisp compact controls. */
function appIcon(Glyph: Icon, name: string, weight: IconWeight = 'duotone') {
  const Component = forwardRef<SVGSVGElement, IconProps>((props, ref) => {
    const labelled = Boolean(props.alt || props['aria-label'] || props['aria-labelledby']);
    return <Glyph ref={ref} size={20} weight={weight} aria-hidden={labelled ? undefined : true}
      focusable="false" {...props} className={`app-icon ${props.className || ''}`}
      data-icon={name} data-icon-library="phosphor" data-icon-glyph={Glyph.displayName}
      data-icon-weight={props.weight || weight} />;
  });
  Component.displayName = `${name}Icon`;
  return Component;
}

